// Край переднего листа главной — S-образная кривая из эскиза в координатах viewBox SHEET_W × SHEET_H
// (лист растянут по экрану, preserveAspectRatio="none"). Кривая начинается слева сверху, проходит
// мимо карточки входа, ныряет под девушку и уходит за правый край. Общая для листа (FrontLayer) и
// обрезки девушки (HeroGirl), чтобы они всегда совпадали.
export const SHEET_W = 1440;
export const SHEET_H = 900;
export const EDGE =
  'M 150 0 C 420 30 590 120 640 330 C 690 540 760 720 960 790 C 1120 845 1300 820 1440 760';

// Область над краем листа (то, что лист не закрывает) в долях 0…1 — для clipPath с
// clipPathUnits="objectBoundingBox": девушка видна только здесь и не просвечивает сквозь лист. Верх
// области — выше экрана (−1): когда край едет вниз вместе с листом, макушка не обрезается.
export const ABOVE_EDGE = `${EDGE.replace(
  /(\d+(?:\.\d+)?) (\d+(?:\.\d+)?)/g,
  (_, x, y) => `${+(x / SHEET_W).toFixed(4)} ${+(y / SHEET_H).toFixed(4)}`,
)} L 1 -1 L 0 -1 Z`;

// Прокрутка к карте опускает лист на эту долю его высоты (HomePage) — обрезка девушки едет вместе
// с ним, иначе между ними открылась бы пустая полоса.
export const SHEET_FLY_SHIFT = 0.3;
